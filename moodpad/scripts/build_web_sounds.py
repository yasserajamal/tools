#!/usr/bin/env python3
"""Bundle sounds/<character>/*.wav into sounds.js as base64, so index.html
works when opened straight from disk (no server needed). Standard library only."""
import base64
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
bank = {}
for wav in sorted((ROOT / "sounds").glob("*/*.wav")):
    bank.setdefault(wav.parent.name, {})[wav.stem] = base64.b64encode(wav.read_bytes()).decode()

out = ROOT / "sounds.js"
out.write_text("// Generated by scripts/build_web_sounds.py from sounds/ (CC0). Do not edit.\n"
               "window.MOODPAD_SOUNDS = " + json.dumps(bank) + ";\n")
print(f"Wrote {out} ({out.stat().st_size // 1024} KB)")
